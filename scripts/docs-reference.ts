import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import ts from "typescript";
import { checkDocumentationLinks, documentationFiles } from "./documentation";

const root = process.cwd();
const entries = ["index", "admin", "headless", "auth"];
const program = ts.createProgram(
  entries.map((name) => `src/${name}.ts`),
  {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    strict: true,
  },
);
const checker = program.getTypeChecker();
const lines = ["<!-- Generated by npm run docs:write. Do not edit this section. -->", ""];
const sourceLink = (node: ts.Node) => {
  const file = path.relative(root, node.getSourceFile().fileName).replaceAll("\\", "/");
  return `[declaration](https://github.com/atomimus/circleso/blob/main/${file})`;
};
for (const entry of entries) {
  const source = program.getSourceFile(`src/${entry}.ts`);
  assert.ok(source);
  const module = checker.getSymbolAtLocation(source);
  assert.ok(module);
  lines.push(`### ${entry === "index" ? "circleso" : `circleso/${entry}`}`, "");
  lines.push("| Export | Kind | Definition |", "| --- | --- | --- |");
  for (const symbol of checker
    .getExportsOfModule(module)
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
    const declaration = target.declarations?.[0];
    assert.ok(declaration, symbol.name);
    lines.push(
      `| \`${symbol.name}\` | ${target.flags & ts.SymbolFlags.Value ? "Runtime" : "Type only"} | ${sourceLink(declaration)} |`,
    );
  }
  lines.push("");
}
lines.push(
  "## Resource call shapes",
  "",
  "Generated from the public facade types, including nested resources and iterators. `options?` is optional; `options` is required. Positional ID types are preserved exactly. `RequestOptions`/`RequestOptionsWithBody` below name internal operation types: use the public `Parameters` recipe above to obtain them. The method/path inventory links every HTTP call to its committed specification. Return types are inferred from that operation; they preserve `undefined`, nullable fields and upstream `unknown` gaps. Iterator calls return async iterables, cookie `WithResponse` calls return `CircleResponse`, and upload workflows return `DirectUploadResult`.",
  "",
);
for (const [moduleName, apiName] of [
  ["adminApi", "AdminApi"],
  ["headlessApi", "HeadlessApi"],
  ["authApi", "AuthApi"],
]) {
  const file = program.getSourceFile(`src/${moduleName}/index.ts`);
  assert.ok(file);
  const declaration = file.statements.find(
    (node): node is ts.TypeAliasDeclaration =>
      ts.isTypeAliasDeclaration(node) && node.name.text === apiName,
  );
  assert.ok(declaration);
  lines.push(`### ${apiName}`, "", "| Call | Definition |", "| --- | --- |");
  const walk = (type: ts.Type, prefix: string, depth: number) => {
    assert.ok(depth < 8);
    for (const property of type.getProperties()) {
      if (property.name === "raw") continue;
      const node = property.valueDeclaration ?? property.declarations?.[0];
      assert.ok(node);
      const value = checker.getTypeOfSymbolAtLocation(property, node);
      const signatures = value.getCallSignatures();
      const name = prefix ? `${prefix}.${property.name}` : property.name;
      if (!signatures.length) {
        walk(value, name, depth + 1);
        continue;
      }
      for (const signature of signatures) {
        const parameters = signature.parameters.map((parameter) => {
          const param = parameter.valueDeclaration;
          assert.ok(param && ts.isParameter(param));
          const annotation =
            param.type?.getText().replace(/\s+/g, " ") ??
            checker.typeToString(checker.getTypeOfSymbolAtLocation(parameter, param));
          return `${param.dotDotDotToken ? "..." : ""}${parameter.name}${param.questionToken || param.initializer ? "?" : ""}: ${annotation}`;
        });
        lines.push(
          `| \`${name}(${parameters.join(", ").replaceAll("|", "&#124;")})\` | ${sourceLink(node)} |`,
        );
      }
    }
  };
  walk(checker.getTypeFromTypeNode(declaration.type), "", 0);
  lines.push("");
}
const file = "docs/api-reference.md";
const source = await readFile(file, "utf8");
const marker = "<!-- PUBLIC API INVENTORY -->";
assert.equal(source.split(marker).length, 2);
const expected = `${source.split(marker)[0]}${marker}\n\n${lines.join("\n")}`;
if (process.argv.includes("--write")) await writeFile(file, expected);
else
  assert.equal(
    source.replaceAll("\r\n", "\n"),
    expected.replaceAll("\r\n", "\n"),
    "Public API reference drift: run npm run docs:write",
  );
const files = documentationFiles(root);
const links = await checkDocumentationLinks(root, files);
console.log(
  `Documentation: ${files.length} tracked Markdown files; ${links} local links/anchors; public exports/resource call shapes match source`,
);
