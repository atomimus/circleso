import type { RequestContract } from "../src/requestInit";
import { failure, type JsonObject, METHODS, object } from "./spec-tools";

export function requestContractFile(name: string): string {
  return `src/generated/${name}.requests.ts`;
}

/** Routing metadata only: generated declarations remain the source of field/value types. */
export function renderRequestContracts(doc: JsonObject): string {
  function resolve(value: unknown, seen = new Set<unknown>()): JsonObject {
    if (!object(value)) throw failure("Expected an object in request contract");
    if (typeof value.$ref !== "string") return value;
    if (seen.has(value)) throw failure("Cyclic request contract reference");
    seen.add(value);
    const resolved = value.$ref
      .slice(2)
      .split("/")
      .reduce<unknown>((current, key) => {
        return object(current)
          ? current[key.replaceAll("~1", "/").replaceAll("~0", "~")]
          : undefined;
      }, doc);
    return resolve(resolved, seen);
  }
  const contracts: Record<string, RequestContract> = {};
  for (const [route, item] of Object.entries(doc.paths as JsonObject).sort(([a], [b]) =>
    a < b ? -1 : a > b ? 1 : 0,
  )) {
    const path = resolve(item);
    for (const method of METHODS) {
      if (!path[method]) continue;
      const operation = resolve(path[method]);
      const parameters = [
        ...((path.parameters as unknown[]) ?? []),
        ...((operation.parameters as unknown[]) ?? []),
      ].map((parameter) => resolve(parameter));
      const query = parameters
        .filter((param) => param.in === "query")
        .map((param) => String(param.name));
      const body = operation.requestBody ? resolve(operation.requestBody) : undefined;
      const schema = body ? resolve(resolve(body.content)["application/json"]).schema : undefined;
      const bodySchema = schema ? resolve(schema) : undefined;
      if (body && (bodySchema?.type !== "object" || !object(bodySchema.properties))) {
        throw failure(`Unsupported facade request body: ${method.toUpperCase()} ${route}`);
      }
      contracts[`${method} ${route}`] = {
        query,
        ...(bodySchema ? { body: Object.keys(bodySchema.properties as JsonObject) } : {}),
        ...(body?.required === true ? { bodyRequired: true } : {}),
      };
    }
  }
  return `// Generated by npm run gen:types. Do not edit.\nimport type { RequestContract } from "../requestInit";\n\nexport const requestContracts: Record<string, RequestContract> = ${JSON.stringify(contracts, null, 2)};\n`;
}
